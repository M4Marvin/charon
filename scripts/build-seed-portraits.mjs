#!/usr/bin/env node
/**
 * Build the bundled starter portraits.
 *
 * Sources are public-domain (or CC0) works from Wikimedia Commons, cropped to
 * a square 512px JPEG and inlined as base64 so every install — npm, Docker,
 * installer, desktop — gets the same first-run characters with no extra files
 * to download. Credits are emitted alongside and shown in NOTICE.
 *
 *   node scripts/build-seed-portraits.mjs
 */
import { mkdirSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const SPECS = [
  {
    key: "ferryman",
    title: "File:Captain-James-Cook.jpg",
    credit: "Portrait of Captain James Cook, public domain (Wikimedia Commons)",
    position: "attention",
  },
  {
    key: "naturalist",
    title: "File:Maria Sibylla Merian portrait.jpeg",
    credit: "Maria Sibylla Merian, public domain (Wikimedia Commons)",
    position: "attention",
  },
  {
    key: "storyteller",
    title: "File:Jan van Bijlert - Young Man Playing the Lute - WGA02186.jpg",
    credit: "Young Man Playing the Lute by Jan van Bijlert, public domain (Wikimedia Commons)",
    position: "attention",
  },
];

const API = "https://commons.wikimedia.org/w/api.php";
const UA = "CharonSeed/1.0 (https://github.com/M4Marvin/charon)";

async function imageInfo(title) {
  const url = `${API}?${new URLSearchParams({
    action: "query",
    format: "json",
    titles: title,
    prop: "imageinfo",
    iiprop: "url|extmetadata",
    iiurlwidth: "900",
  })}`;
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  const json = await res.json();
  const page = Object.values(json.query?.pages ?? {})[0];
  const info = page?.imageinfo?.[0];
  if (!info) throw new Error(`No image for ${title}`);
  return info;
}

mkdirSync(".review/packaging/portraits", { recursive: true });

const entries = [];
for (const spec of SPECS) {
  const info = await imageInfo(spec.title);
  const src = info.thumburl ?? info.url;
  const download = await fetch(src, { headers: { "User-Agent": UA } });
  if (!download.ok) throw new Error(`${spec.key}: ${download.status}`);
  const bytes = Buffer.from(await download.arrayBuffer());
  const jpeg = await sharp(bytes)
    .resize(512, 512, { fit: "cover", position: spec.position ?? "attention" })
    .jpeg({ quality: 84, mozjpeg: true })
    .toBuffer();
  writeFileSync(`.review/packaging/portraits/${spec.key}.jpg`, jpeg);
  entries.push({ key: spec.key, credit: spec.credit, base64: jpeg.toString("base64") });
  console.log(`${spec.key}: ${(jpeg.length / 1024).toFixed(0)} KB from ${spec.title}`);
}

const out = [
  "// GENERATED by scripts/build-seed-portraits.mjs — do not edit by hand.",
  "// Public-domain portraits from Wikimedia Commons, inlined so every install",
  "// ships the same first-run characters without extra files.",
  "",
  "export type SeedPortrait = { credit: string; base64: string };",
  "",
  "export const SEED_PORTRAITS: Record<string, SeedPortrait> = {",
  ...entries.map(
    (entry) =>
      `  ${entry.key}: {\n    credit: ${JSON.stringify(entry.credit)},\n    base64: "${entry.base64}",\n  },`,
  ),
  "};",
  "",
].join("\n");

writeFileSync("src/server/seed-portraits.ts", out);
console.log(`Wrote src/server/seed-portraits.ts (${(out.length / 1024).toFixed(0)} KB)`);
